function buildDeck() {
  const deck = MAJORS.map(([zh, en, element, upKey, up, revKey, rev], i) => ({
    id: `major-${i}`, arcana: 'major', number: i, zh, en, element, suit: null,
    rank: null, court: false, upKey, up, revKey, rev,
  }));
  for (const suit of SUITS) {
    MINORS[suit.key].forEach(([upKey, up, revKey, rev], i) => {
      const [rankZh, rankEn] = RANKS[i];
      deck.push({
        id: `${suit.key}-${i + 1}`, arcana: 'minor', number: i + 1,
        zh: `${suit.zh}${rankZh}`, en: `${rankEn} of ${suit.en}`,
        element: suit.element, suit: suit.key, suitZh: suit.zh,
        rank: i + 1, court: i >= 10, upKey, up, revKey, rev,
      });
    });
  }
  return deck;
}

