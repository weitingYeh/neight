function buildDeck() {
  const deck = MAJORS.map(([zh, en, element, img, upKey, up, revKey, rev, vUp, vRev], i) => ({
    id: `major-${i}`, arcana: 'major', number: i, zh, en, element, suit: null,
    rank: null, court: false, img, upKey, up, revKey, rev, vUp, vRev,
  }));
  for (const suit of SUITS) {
    MINORS[suit.key].forEach(([img, upKey, up, revKey, rev, vUp, vRev], i) => {
      const [rankZh, rankEn] = RANKS[i];
      deck.push({
        id: `${suit.key}-${i + 1}`, arcana: 'minor', number: i + 1,
        zh: `${suit.zh}${rankZh}`, en: `${rankEn} of ${suit.en}`,
        element: suit.element, suit: suit.key, suitZh: suit.zh,
        rank: i + 1, court: i >= 10, img, upKey, up, revKey, rev, vUp, vRev,
      });
    });
  }
  return deck;
}

